/** Providers keyed by slug for quick lookup. */
export const PROVIDERS_BY_SLUG: Record<string, ModelProvider> = Object.fromEntries(
  MODEL_PROVIDERS.map((p) => [p.slug, p]),
);

/** Models keyed by their globally-unique modelId. */
export const MODELS_BY_ID: Record<string, AiModel> = Object.fromEntries(
  AI_MODELS.map((m) => [m.modelId, m]),
);

export function getProvider(slug: ProviderSlug): ModelProvider | null {
  return PROVIDERS_BY_SLUG[slug] ?? null;
}

export function getModel(modelId: string): AiModel | null {
  return MODELS_BY_ID[modelId] ?? null;
}

export function modelsByProvider(slug: ProviderSlug): AiModel[] {
  return AI_MODELS.filter((m) => m.providerSlug === slug);
}
