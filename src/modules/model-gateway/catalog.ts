/** Default capability set; each model overrides the flags it needs. */
type ModelSeed = Omit<
  AiModel,
  | "status"
  | "supportsText"
  | "supportsVision"
  | "supportsAudio"
  | "supportsTools"
  | "supportsJson"
  | "supportsStreaming"
  | "supportsReasoning"
  | "supportsCaching"
  | "priceCheckedAt"
> &
  Partial<
    Pick<
      AiModel,
      | "status"
      | "supportsText"
      | "supportsVision"
      | "supportsAudio"
      | "supportsTools"
      | "supportsJson"
      | "supportsStreaming"
      | "supportsReasoning"
      | "supportsCaching"
    >
  >;

